def insertion_sort(arr):
    """Сортировка вставками.

    Проходим по списку слева направо и вставляем каждый элемент
    на своё место среди уже отсортированных элементов слева.

    Сложность:
        Время:  O(n^2) в худшем/среднем случае, O(n) если список уже отсортирован
        Память: O(1) — сортировка на месте (in-place)
    """
    for i in range(1, len(arr)):
        key = arr[i]        # элемент, который нужно вставить
        j = i - 1

        # Сдвигаем элементы, которые больше key, на одну позицию вправо
        while j >= 0 and arr[j] > key:
            arr[j + 1] = arr[j]
            j -= 1

        # Вставляем key на найденное место
        arr[j + 1] = key

    return arr


if __name__ == "__main__":
    data = [12, 11, 13, 5, 6]
    print("Исходный список: ", data)
    insertion_sort(data)
    print("Отсортированный: ", data)
